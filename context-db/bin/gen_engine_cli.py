#!/usr/bin/env python3
"""gen_engine_cli.py — generate `docs/engine-cli.md`, the engine's CLI reference.

The reference is DERIVED, never hand-written: it is `make -C $BATON/context-db help` (the Makefile's comment
header) followed by `python3 context-db/bin/<tool>.py --help` for every engine tool that answers `--help` with
exit 0. A tool that has no argparse (exit != 0 on `--help`) is listed with its module docstring instead, so the
doc never invents a command. `tests/test_engine_cli_doc.py` regenerates the doc and fails when the committed
copy differs, so drift fails CI.

  python3 $BATON/context-db/bin/gen_engine_cli.py            # rewrite docs/engine-cli.md
  python3 $BATON/context-db/bin/gen_engine_cli.py --check    # exit 3 when docs/engine-cli.md is out of date
  python3 $BATON/context-db/bin/gen_engine_cli.py --stdout   # print the doc instead of writing it
  make -C $BATON/context-db engine-cli-doc                   # the Makefile target

Determinism: every subprocess runs with COLUMNS=80 (argparse wraps to the terminal width), a CONTEXT_ROOT that
does not exist (so no machine's env store leaks into the text — the tools' "no env store" hint goes to stderr,
which is dropped) and a fixed locale, so two machines with the same Python produce the same bytes. Stdlib only.
"""
from __future__ import annotations
import argparse
import ast
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENGINE = HERE.parent
KIT = ENGINE.parent
DOC = KIT / "docs" / "engine-cli.md"

# The tools the reference covers, in the order they appear. A tool answers `--help` (argparse) or is listed with
# its docstring — detected by the exit code at generation time, never assumed.
TOOLS = (
    "kb.py",
    "kit_profile.py",
    "kit_verify.py",
    "review_gate.py",
    "review_evidence.py",
    "eval_check.py",
    "personal.py",
    "session.py",
    "session_stats.py",
    "session_retro.py",
    "gen_sessions.py",
    "gen_index.py",
    "verify.py",
    "commit_style.py",
    "migrate_frontmatter.py",
    "check_links.py",
    "transcripts.py",
    "leak_shapes.py",
    "gen_eval_rules.py",
)
# Tools without an argument parser: listed by docstring, never executed (running them would do their job, not print
# help — gen_eval_rules.py would rewrite the eval prompts; transcripts.py and leak_shapes.py are importable
# libraries with no `__main__` at all).
DOCSTRING_ONLY = ("kit_profile.py", "gen_index.py", "verify.py", "gen_eval_rules.py", "transcripts.py", "leak_shapes.py")

HEADER = """# Engine CLI reference

<!-- GENERATED by context-db/bin/gen_engine_cli.py — do not edit by hand. -->

**Generated** from `make -C $BATON/context-db help` (`$BATON` is the kit root — `docs/glossary.md`) and every
engine tool's `--help` by `context-db/bin/gen_engine_cli.py`. Regenerate with `make -C $BATON/context-db engine-cli-doc`;
`context-db/tests/test_engine_cli_doc.py` fails when this file drifts from the generator's output.
Every tool is `python3 $BATON/context-db/bin/<tool>` from the workspace root and needs nothing but
the standard library; `CONTEXT_ROOT=<path>/.context` points one at another content root.
"""


def run_env() -> dict[str, str]:
    env = dict(os.environ)
    env.update(
        COLUMNS="80",
        LINES="24",
        CONTEXT_ROOT=str(Path(tempfile.gettempdir()) / "gen-engine-cli-no-store" / ".context"),
        PYTHONDONTWRITEBYTECODE="1",
        PYTHONIOENCODING="utf-8",
        LC_ALL="C.UTF-8",
        LANG="C.UTF-8",
    )
    env.pop("CLAUDE_CODE_SESSION_ID", None)  # a tool must not read this session's transcript into the doc
    return env


def make_help() -> str:
    p = subprocess.run(["make", "--no-print-directory", "-C", str(ENGINE), "help"],
                       capture_output=True, text=True, encoding="utf-8", env=run_env(), check=True)
    lines = []
    for line in p.stdout.splitlines():
        lines.append(line[2:] if line.startswith("# ") else line.lstrip("#"))
    return "\n".join(lines).rstrip() + "\n"


def tool_help(tool: str) -> tuple[int, str]:
    p = subprocess.run([sys.executable, str(HERE / tool), "--help"], capture_output=True, text=True,
                       encoding="utf-8", env=run_env(), cwd=str(KIT))
    return p.returncode, p.stdout


def docstring(tool: str) -> str:
    return (ast.get_docstring(ast.parse((HERE / tool).read_text(encoding="utf-8"))) or "").rstrip()


def fence(text: str) -> str:
    return "```text\n" + text.rstrip("\n") + "\n```\n"


def render() -> str:
    out = [HEADER, "## `make -C $BATON/context-db help`\n", fence(make_help())]
    for tool in TOOLS:
        out.append(f"## `{tool}`\n")
        if tool in DOCSTRING_ONLY:  # never run: no argparse, `--help` would execute the tool (gen_index.py writes INDEX.md)
            out.append("No `--help` (the tool has no argument parser); the usage is the module docstring:\n\n" + fence(docstring(tool)))
            continue
        rc, text = tool_help(tool)
        if rc == 0 and text.strip():
            out.append(fence(text))
        else:
            out.append(f"`--help` failed (exit {rc}); the usage is the module docstring:\n\n" + fence(docstring(tool)))
    return "\n".join(out)


def norm(text: str) -> str:
    """Whitespace-insensitive form: argparse re-flows help text per Python version, the words do not change —
    except one heading argparse itself renamed (`optional arguments:` before 3.10, `options:` from 3.10 on),
    canonicalised here so the committed doc matches `--help` on every floor-to-latest Python the kit supports."""
    text = text.replace("optional arguments:", "options:")
    return re.sub(r"\s+", " ", text).strip()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_engine_cli.py", description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="compare with the committed doc; exit 3 when it differs, write nothing")
    g.add_argument("--stdout", action="store_true", help="print the doc instead of writing it")
    ap.add_argument("--out", type=Path, default=DOC, help=f"where to write (default docs/engine-cli.md)")
    a = ap.parse_args(argv)
    text = render()
    if a.stdout:
        sys.stdout.write(text)
        return 0
    if a.check:
        have = a.out.read_text(encoding="utf-8") if a.out.is_file() else ""
        if norm(have) != norm(text):  # argparse wraps `--help` differently per Python version: compare the words, not the layout
            print(f"{a.out.relative_to(KIT) if a.out.is_relative_to(KIT) else a.out}: out of date — run "
                  "`make -C $BATON/context-db engine-cli-doc`", file=sys.stderr)
            return 3
        print(f"{a.out.name}: current")
        return 0
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out.relative_to(KIT) if a.out.is_relative_to(KIT) else a.out} ({len(text.encode())} B)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
